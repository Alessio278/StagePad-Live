"""Generate vector UI/logo assets and independently sampled Windows ICO frames.
Requires Pillow. Run from any directory with python3 tools/Generate-Icon.py.
"""
from pathlib import Path
import io, re, struct
from PIL import Image, ImageDraw
root=Path(__file__).resolve().parents[1]
assets=root/'StagePad.App'/'Assets'
path='M 72 29 C 66 19 51 16 39 20 C 25 24 21 41 31 50 C 37 56 47 57 57 60 C 63 62 64 68 59 72 C 51 78 36 74 29 66 L 20 77 C 32 91 55 95 71 83 C 87 71 85 51 67 44 C 58 40 48 40 42 36 C 37 32 42 27 49 27 C 55 27 61 30 65 34 Z'
tokens=re.findall(r'[MCLZ]|-?\d+(?:\.\d+)?',path);points=[];i=0;position=(0,0)
while i<len(tokens):
 command=tokens[i];i+=1
 if command in ('M','L'):
  position=(float(tokens[i]),float(tokens[i+1]));i+=2;points.append(position)
 elif command=='C':
  p0=position;p1=tuple(map(float,tokens[i:i+2]));p2=tuple(map(float,tokens[i+2:i+4]));p3=tuple(map(float,tokens[i+4:i+6]));i+=6
  for step in range(1,401):
   t=step/400;u=1-t
   points.append(tuple(u*u*u*p0[j]+3*u*u*t*p1[j]+3*u*t*t*p2[j]+t*t*t*p3[j] for j in (0,1)))
  position=p3
xs=[p[0] for p in points];ys=[p[1] for p in points]
scale=min(80/(max(xs)-min(xs)),82/(max(ys)-min(ys)))
tx=50-(min(xs)+max(xs))*scale/2;ty=50-(min(ys)+max(ys))*scale/2
scale,tx,ty=[round(x,9) for x in (scale,tx,ty)]
(assets/'StagePad.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 100 100"><rect width="100" height="100" rx="22" fill="#75E2C1"/><path d="{path}" transform="matrix({scale} 0 0 {scale} {tx} {ty})" fill="#FFFFFF"/></svg>\n')
def render(size):
 n=size*8
 image=Image.new('RGBA',(n,n));draw=ImageDraw.Draw(image)
 draw.rounded_rectangle((0,0,n-1,n-1),radius=round(n*.22),fill='#75E2C1')
 draw.polygon([((x*scale+tx)*n/100,(y*scale+ty)*n/100) for x,y in points],fill='#FFFFFF')
 return image.resize((size,size),Image.Resampling.LANCZOS)
render(1024).save(assets/'StagePad.png')
# Each ICO frame is rendered directly from geometry, never from a resized PNG.
sizes=[16,20,24,28,32,40,48,64,96,128,192,256];blobs=[]
for size in sizes:
 buffer=io.BytesIO();render(size).save(buffer,format='PNG');blobs.append(buffer.getvalue())
header=struct.pack('<HHH',0,1,len(sizes));offset=6+16*len(sizes);entries=[]
for size,blob in zip(sizes,blobs):
 entries.append(struct.pack('<BBBBHHII',size if size<256 else 0,size if size<256 else 0,0,0,1,32,len(blob),offset));offset+=len(blob)
(assets/'StagePad.ico').write_bytes(header+b''.join(entries)+b''.join(blobs))
# WPF uses the original vector at the actual display DPI.
(root/'StagePad.App'/'Ui'/'LogoImage.cs').write_text('''// Generated by tools/Generate-Icon.py: keep UI and packaged artwork identical.
using System.Windows;
using System.Windows.Media;
namespace StagePad.App;
internal static class LogoImage
{
    public static ImageSource Create()
    {
        var group=new DrawingGroup();
        group.Children.Add(new GeometryDrawing(new SolidColorBrush(Color.FromRgb(117,226,193)),null,new RectangleGeometry(new Rect(0,0,100,100),22,22)));
        var letter=Geometry.Parse("'''+path+'''").Clone();
        letter.Transform=new MatrixTransform('''+f'{scale},0,0,{scale},{tx},{ty}'+''');
        group.Children.Add(new GeometryDrawing(Brushes.White,null,letter));
        var image=new DrawingImage(group);image.Freeze();return image;
    }
}
''')
